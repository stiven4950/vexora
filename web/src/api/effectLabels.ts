/** El nombre legible de un efecto; si no está en la lista, el interno sin guiones bajos y con mayúscula inicial. */
export function effectLabel(name: string): string {
  const base = name.replace(/ \((espejo|fijado)\)/g, '').trim();
  if (Object.prototype.hasOwnProperty.call(EFFECT_LABELS, base)) {
    const label = EFFECT_LABELS[base];
    if (label !== undefined) return label;
  }
  const plain = base.replace(/_/g, ' ').trim();
  return plain.charAt(0).toUpperCase() + plain.slice(1);
}
